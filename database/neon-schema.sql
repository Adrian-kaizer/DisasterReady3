CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL,
    password_salt TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'user'
        CHECK (role IN ('user', 'admin')),
    status TEXT NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'inactive')),
    profile_picture_data TEXT,
    profile_picture_mime TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_unique
    ON users (LOWER(email));

CREATE UNIQUE INDEX IF NOT EXISTS one_admin_account
    ON users (role)
    WHERE role = 'admin';

CREATE TABLE IF NOT EXISTS auth_sessions (
    token_hash TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS auth_sessions_expiration_idx
    ON auth_sessions (expires_at);

CREATE TABLE IF NOT EXISTS auth_attempts (
    attempt_key TEXT PRIMARY KEY,
    window_started_at TIMESTAMPTZ NOT NULL,
    attempt_count INTEGER NOT NULL CHECK (attempt_count > 0)
);

CREATE TABLE IF NOT EXISTS location_search_rate (
    singleton BOOLEAN PRIMARY KEY DEFAULT TRUE CHECK (singleton),
    next_request_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

INSERT INTO location_search_rate (singleton)
VALUES (TRUE)
ON CONFLICT (singleton) DO NOTHING;

CREATE TABLE IF NOT EXISTS location_search_cache (
    query TEXT PRIMARY KEY,
    results JSONB NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL
);

CREATE OR REPLACE FUNCTION consume_auth_attempt(
    requested_key TEXT,
    max_attempts INTEGER,
    window_seconds INTEGER
)
RETURNS BOOLEAN
LANGUAGE plpgsql
AS $$
DECLARE
    current_count INTEGER;
BEGIN
    INSERT INTO auth_attempts (attempt_key, window_started_at, attempt_count)
    VALUES (requested_key, NOW(), 1)
    ON CONFLICT (attempt_key) DO UPDATE
    SET
        attempt_count = CASE
            WHEN auth_attempts.window_started_at
                + make_interval(secs => window_seconds) <= NOW()
            THEN 1
            ELSE auth_attempts.attempt_count + 1
        END,
        window_started_at = CASE
            WHEN auth_attempts.window_started_at
                + make_interval(secs => window_seconds) <= NOW()
            THEN NOW()
            ELSE auth_attempts.window_started_at
        END
    RETURNING attempt_count INTO current_count;

    RETURN current_count <= max_attempts;
END;
$$;

CREATE OR REPLACE FUNCTION reserve_location_search_slot()
RETURNS INTEGER
LANGUAGE plpgsql
AS $$
DECLARE
    scheduled_at TIMESTAMPTZ;
    request_now TIMESTAMPTZ := clock_timestamp();
BEGIN
    SELECT next_request_at
    INTO scheduled_at
    FROM location_search_rate
    WHERE singleton = TRUE
    FOR UPDATE;

    scheduled_at := GREATEST(scheduled_at, request_now);

    UPDATE location_search_rate
    SET next_request_at = scheduled_at + INTERVAL '1 second'
    WHERE singleton = TRUE;

    RETURN GREATEST(
        0,
        CEIL(EXTRACT(EPOCH FROM (scheduled_at - clock_timestamp())) * 1000)::INTEGER
    );
END;
$$;


-- Each signed-in user can save one private map pin for their own reference.
CREATE TABLE IF NOT EXISTS user_saved_locations (
    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    label TEXT NOT NULL CHECK (char_length(label) BETWEEN 1 AND 160),
    latitude DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- User-owned preparedness checklist state.
CREATE TABLE IF NOT EXISTS checklist_progress (
    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    items JSONB NOT NULL DEFAULT '{}'::jsonb,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Hazard reports are owned by the reporting account until reviewed by an administrator.
CREATE TABLE IF NOT EXISTS hazard_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    location TEXT NOT NULL CHECK (char_length(location) BETWEEN 1 AND 240),
    hazard_type TEXT NOT NULL CHECK (char_length(hazard_type) BETWEEN 1 AND 80),
    description TEXT NOT NULL CHECK (char_length(description) BETWEEN 1 AND 2000),
    status TEXT NOT NULL DEFAULT 'unverified'
        CHECK (status IN ('unverified', 'reviewing', 'verified', 'resolved')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS hazard_reports_user_created_idx
    ON hazard_reports (user_id, created_at DESC);

-- Shared monitoring stations; only administrator accounts may manage them.
CREATE TABLE IF NOT EXISTS flood_stations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (char_length(name) BETWEEN 1 AND 120),
    location TEXT NOT NULL CHECK (char_length(location) BETWEEN 1 AND 240),
    warning_level DOUBLE PRECISION NOT NULL CHECK (warning_level > 0),
    critical_level DOUBLE PRECISION NOT NULL CHECK (critical_level > warning_level),
    created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS flood_stations_name_location_lower_unique
    ON flood_stations (LOWER(name), LOWER(location));
CREATE TABLE IF NOT EXISTS flood_readings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_id BIGINT NOT NULL REFERENCES flood_stations(id) ON DELETE CASCADE,
    water_level DOUBLE PRECISION NOT NULL CHECK (water_level >= 0),
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    recorded_by BIGINT REFERENCES users(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS flood_readings_station_time_idx
    ON flood_readings (station_id, recorded_at DESC);
